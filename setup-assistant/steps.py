def human_text(support_username: str) -> str:
    """Экран «Позвать человека»."""
    if support_username:
        line = f"Напишите нам в <code>@{support_username}</code> - поможем разобраться."
    else:
        line = "Напишите человеку, у которого вы приобрели этого ассистента, - он поможет разобраться."
    return (
        "<b>Звать человека - это нормально, мы рядом.</b>\n\n"
        f"{line}\n\n"
        "Чтобы помочь быстрее, укажите:\n"
        "• на каком шаге застряли;\n"
        "• что уже сделали;\n"
        "• что видите на экране (скриншот приветствуется).\n\n"
        "И на всякий случай: не присылайте никому golden_key и токены - "
        "они нужны только консоли Cardinal на вашем компьютере."
    )


